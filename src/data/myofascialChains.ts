export type TransmissionMechanism =
  | 'myotendinous_expansion' // 肌腱筋膜扩张部直接胶原连续（如肱二头肌腱膜、菱形-前锯肌吊带）
  | 'bony_pulley_pivot'      // 骨性滑轮转换（如肩胛骨喙突前倾拉拽 → 肩胛内侧缘与胸椎棘突离心受拉）
  | 'retinacular_hub'        // 支持带与肌间隔汇合（如腕管屈肌支持带、肱骨内外侧肌间隔）
  | 'antagonist_couple';     // 同平面拮抗序列失衡（去程向心缩短锁死 → 回程离心紧绷受拉）

export interface BiomechanicalEdge {
  id: string;
  from: string; // Upstream / tension source SteccoNode ID
  to: string;   // Downstream / tension receiver SteccoNode ID
  weight: number; // 0..1 force transmission ratio (based on Stecco / Myers fascial continuity)
  mechanism: TransmissionMechanism;
  mechanismLabelZh: string;
  anatomicalBridgeZh: string;
  clinicalExplanation: string;
}

